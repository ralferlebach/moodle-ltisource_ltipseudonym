class refusal extends \Exception {
    /**
     * Constructor.
     *
     * @param int $httpcode HTTP status code of the answer
     * @param string $reason technical reason, never containing an identifier of a user
     */
    public function __construct(int $httpcode, string $reason) {
        parent::__construct($reason, $httpcode);
    }
}
